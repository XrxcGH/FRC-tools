/**
 * Measurement harness.
 *
 * The review's required addition #4: ship the numbers the design asserts as
 * MEASURED, or ship the cell visibly empty. Filled-in guesses get treated as
 * spec by whoever implements them.
 *
 * This measures everything measurable without radio hardware — wire sizes,
 * reconciliation round trips and overhead, and crypto throughput. It ends by
 * printing, explicitly, the things it CANNOT measure here, so those stay
 * visibly open rather than quietly plausible.
 *
 *   node packages/courier-core/bench/measure.ts [--md]
 */

import {
  RecordStore,
  reconcile,
  storesConverged,
  makeRecord,
  sealRecord,
  openEnvelope,
  envelopeSize,
  encodeRecord,
  generateDeviceKey,
  generateMeshKey,
  mintScoutPseudonym,
  parseMatchKey,
  type DeviceKeyPair,
  type KeyResolver,
} from '../src/index.ts';
import { toHex } from '../src/hash.ts';

const asMarkdown = process.argv.includes('--md');
const out: string[] = [];
const say = (s = ''): void => {
  out.push(s);
};

/* ------------------------------------------------------------- fixtures --- */

const meshKey = generateMeshKey();
const devices = new Map<string, DeviceKeyPair>();
function device(name: string): DeviceKeyPair {
  let d = devices.get(name);
  if (!d) {
    d = generateDeviceKey('software');
    devices.set(name, d);
  }
  return d;
}
const resolver: KeyResolver = (kid) => {
  for (const d of devices.values()) if (toHex(d.kid) === toHex(kid)) return d.publicKey;
  return undefined;
};

function rng(seed: number): () => number {
  let s = seed >>> 0;
  return () => {
    s ^= s << 13;
    s >>>= 0;
    s ^= s >> 17;
    s ^= s << 5;
    s >>>= 0;
    return s / 0x100000000;
  };
}

const EVENT = '2027mose';
const TEAMS = [8793, 9143, 254, 1678, 118, 2056, 3128, 5940];

function sealOne(scout: number, match: number, bodyLen: number, rand: () => number): Uint8Array {
  const body = new Uint8Array(bodyLen);
  for (let i = 0; i < bodyLen; i++) body[i] = Math.floor(rand() * 256);
  const record = makeRecord({
    eventKey: EVENT,
    match: parseMatchKey(`${EVENT}_qm${match}`).packed,
    team: TEAMS[(match + scout) % TEAMS.length]!,
    scout: mintScoutPseudonym(`scout-${scout}`, EVENT, meshKey),
    schema: 'demo.scout.v1',
    body,
    sealedAt: 1_800_000_000_000 + match * 1000 + scout,
  });
  return sealRecord(record, device(`tablet-${scout}`));
}

/** Build a store of `matches x scouts` records, omitting indices in `skip`. */
function buildStore(matches: number, scouts: number, seed: number, skip?: Set<number>): RecordStore {
  const store = new RecordStore();
  const rand = rng(seed);
  let i = 0;
  for (let m = 1; m <= matches; m++) {
    for (let s = 0; s < scouts; s++) {
      const len = 40 + Math.floor(rand() * 80);
      i++;
      if (skip?.has(i)) continue;
      store.admit(sealOne(s, m, len, rng(seed * 1000 + i)), resolver);
    }
  }
  return store;
}

