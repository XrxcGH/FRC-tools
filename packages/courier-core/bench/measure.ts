/* 1. Envelope size ---------------------------------------------------------- */

say('## 1. Envelope size vs body size');
say();
say('| Body bytes | Record payload | Envelope | Overhead |');
say('|---:|---:|---:|---:|');
const rand1 = rng(42);
for (const bodyLen of [0, 16, 40, 80, 120, 256, 1024]) {
  const body = new Uint8Array(bodyLen);
  for (let i = 0; i < bodyLen; i++) body[i] = Math.floor(rand1() * 256);
  const record = makeRecord({
    eventKey: EVENT,
    match: parseMatchKey(`${EVENT}_qm1`).packed,
    team: 8793,
    scout: mintScoutPseudonym('scout-0', EVENT, meshKey),
    schema: 'demo.scout.v1',
    body,
    sealedAt: 1_800_000_000_000,
  });
  const env = sealRecord(record, device('tablet-0'));
  const payload = encodeRecord(record).length;
  if (envelopeSize(record) !== env.length) {
    throw new Error(`estimator drift: ${envelopeSize(record)} != ${env.length}`);
  }
  say(`| ${bodyLen} | ${payload} | ${env.length} | ${env.length - bodyLen} |`);
}
say();
say(
  'Overhead is 186-191 bytes and steps only where CBOR length headers widen (186 below a 24-byte ' +
    'body, 188 below 256, 191 beyond). It is 101 bytes of record fields — dominated by two ' +
    '32-byte hashes — plus 21 bytes of COSE structure and a 64-byte Ed25519 signature. That is ' +
    'the price of every record being independently verifiable, which is what lets a device accept ' +
    'a record relayed by a peer it has no reason to trust.',
);
say();

/* 2. Event-day volume ------------------------------------------------------- */

say('## 2. A full event day');
say();
const t0 = performance.now();
const full = buildStore(80, 8, 5);
const buildMs = performance.now() - t0;
const stats = full.stats();
say('| Quantity | Value |');
say('|---|---:|');
say(`| Records (80 quals x 8 scouts) | ${stats.records} |`);
say(`| Distinct observations | ${stats.observations} |`);
say(`| Distinct scouts | ${stats.scouts} |`);
say(`| Total envelope bytes | ${(stats.bytes / 1024).toFixed(1)} kB |`);
say(`| Mean envelope | ${Math.round(stats.bytes / stats.records)} B |`);
say(`| Seal + verify + store, wall clock | ${buildMs.toFixed(0)} ms |`);
say(`| Per record | ${(buildMs / stats.records).toFixed(2)} ms |`);
say();
const kB = stats.bytes / 1024;
say('Transfer time for the whole day\'s data, at the throughput figures the design uses:');
say();
say('| Path | Assumed rate | Time for full day |');
say('|---|---:|---:|');
for (const [name, rate] of [
  ['BLE GATT, iOS peripheral (design figure)', 12],
  ['BLE GATT, Android central (design figure)', 25],
  ['USB mass storage', 5000],
] as const) {
  const secs = kB / rate;
  say(`| ${name} | ${rate} kB/s | ${secs < 1 ? `${(secs * 1000).toFixed(0)} ms` : `${secs.toFixed(1)} s`} |`);
}
say();
say(
  'Bandwidth is not the constraint. A full competition day of scouting moves in well under a ' +
    'minute even on the slowest assumed path — which is the measured basis for cutting L2CAP ' +
    'from v1 (D-13). Connection setup and radio duty cycle are what matter.',
);
say();

/* 3. Reconciliation --------------------------------------------------------- */

say('## 3. Reconciliation cost vs symmetric difference');
say();
say(
  'Two stores, 640 records each at full overlap, then diverged by the stated amount ' +
    '(half missing from each side). "Overhead" excludes the transferred records themselves — ' +
    'it is what the protocol costs to *find* the difference.',
);
say();
say('| Symmetric difference | Messages | Round trips | Total bytes | Protocol overhead | Converged |');
say('|---:|---:|---:|---:|---:|---|');

const RECORD_BYTES = Math.round(stats.bytes / stats.records);
for (const diff of [0, 2, 10, 50, 100, 200, 400]) {
  const half = Math.floor(diff / 2);
  const skipA = new Set<number>();
  const skipB = new Set<number>();
  for (let i = 0; i < half; i++) skipA.add(100 + i);
  for (let i = 0; i < diff - half; i++) skipB.add(300 + i);

  const a = buildStore(80, 8, 5, skipA);
  const b = buildStore(80, 8, 5, skipB);
  const res = reconcile(a, b, resolver);
  const overhead = res.bytes - res.admitted * RECORD_BYTES;
  say(
    `| ${diff} | ${res.rounds} | ${Math.ceil(res.rounds / 2)} | ${(res.bytes / 1024).toFixed(1)} kB | ` +
      `${(Math.max(0, overhead) / 1024).toFixed(1)} kB | ${
        res.converged && storesConverged(a, b) ? 'yes' : 'NO'
      } |`,
  );
}
say();
say(
  'Round trips stay flat as the difference grows, which is the property that matters on a ' +
    'transport where each round trip costs ~1.8 s of connection setup. Protocol overhead is ' +
    'dominated by the one truncated-id list (8 bytes per record held), so it scales with store ' +
    'size rather than difference size — the deliberate trade made by `LEAF_THRESHOLD` (2048), ' +
    'which buys a round trip with a few kB.',
);
say();

/* 4. Crypto throughput ------------------------------------------------------ */

say('## 4. Crypto throughput');
say();
const body = new Uint8Array(80).fill(7);
const rec = makeRecord({
  eventKey: EVENT,
  match: parseMatchKey(`${EVENT}_qm1`).packed,
  team: 8793,
  scout: mintScoutPseudonym('scout-0', EVENT, meshKey),
  schema: 'demo.scout.v1',
  body,
  sealedAt: 1_800_000_000_000,
});
const dev = device('tablet-0');

const N = 500;
const ts = performance.now();
for (let i = 0; i < N; i++) sealRecord(rec, dev);
const signMs = (performance.now() - ts) / N;

const env = sealRecord(rec, dev);
const tv = performance.now();
for (let i = 0; i < N; i++) openEnvelope(env, resolver);
const verifyMs = (performance.now() - tv) / N;

say('| Operation | Per record | Records/second |');
say('|---|---:|---:|');
say(`| Seal (encode + Ed25519 sign) | ${signMs.toFixed(2)} ms | ${Math.round(1000 / signMs)} |`);
say(`| Open (verify + decode + validate) | ${verifyMs.toFixed(2)} ms | ${Math.round(1000 / verifyMs)} |`);
say();
say(
  `On this machine a peer can verify a full event day (${stats.records} records) in ` +
    `${((verifyMs * stats.records) / 1000).toFixed(1)} s. A 2016-class Chromebook or a low-end ` +
    'Android tablet should be assumed several times slower — see the open items below, because ' +
    'that factor has not been measured on real hardware.',
);
say();

